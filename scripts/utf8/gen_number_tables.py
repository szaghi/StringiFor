#!/usr/bin/env python3
"""Generate the tables of powers of ten of the number conversions of StringiFor (exact integer arithmetic, no input).

Usage: gen_number_tables.py          write src/lib/stringifor_number_tables.F90
       gen_number_tables.py --check  fail if the committed module differs

Tables (columns: high and low 64 bits, as two's complement integers), each a power normalized to 128 bits:
  POW5_TABLE(q), q = -342..308   parsing (Lemire, Number Parsing at a Gigabyte per Second, 2021): truncated for q >= 0;
                                 for q < 0 the reciprocal, floor + 1, keeping 128 bits
  POW10_TABLE(k), k = -292..324  printing (Giulietti, The Schubfach way to render doubles, 2020): 10**k rounded up
"""

from __future__ import annotations

import argparse
import sys
from fractions import Fraction
from pathlib import Path

MODULE = Path(__file__).resolve().parents[2] / "src" / "lib" / "stringifor_number_tables.F90"
MASK = (1 << 64) - 1
BLOCK = 60  # rows per constructor, to stay within the continuation lines of the standard


def pow5(q: int) -> int:
    """Return the 128 bit parsing entry of 5**q."""
    if q >= 0:
        value = 5**q
        while value < 1 << 127:
            value *= 2
        while value >= 1 << 128:
            value //= 2
        return value
    power = 5**-q
    z = power.bit_length() if power != 1 << (power.bit_length() - 1) else power.bit_length() - 1
    if q >= -27:
        return 2 ** (z + 127) // power + 1
    value = 2 ** (2 * z + 128) // power + 1
    while value >= 1 << 128:
        value //= 2
    return value


def pow10(k: int) -> int:
    """Return 10**k rounded up to 128 significant bits."""
    value = Fraction(10) ** k
    e = value.numerator.bit_length() - value.denominator.bit_length()
    while Fraction(2) ** e > value:
        e -= 1
    while Fraction(2) ** (e + 1) <= value:
        e += 1
    scaled = value * Fraction(2) ** (127 - e)
    return -((-scaled.numerator) // scaled.denominator)


def literal(word: int) -> str:
    """Return a 64 bit word as a Fortran signed literal."""
    signed = word - (1 << 64) if word >> 63 else word
    if signed == -(1 << 63):
        return "(-9223372036854775807_I8P-1_I8P)"
    return f"{signed}_I8P"


def table(name: str, first: int, last: int, entry) -> list[str]:
    """Return the declarations of one table, in blocks."""
    out = []
    blocks = []
    for start in range(first, last + 1, BLOCK):
        stop = min(start + BLOCK - 1, last)
        words = [w for k in range(start, stop + 1) for w in (entry(k) >> 64, entry(k) & MASK)]
        block = f"{name}_{len(blocks) + 1}"
        blocks.append(block)
        rows = [", ".join(literal(w) for w in words[i : i + 4]) for i in range(0, len(words), 4)]
        out.append(f"integer(I8P), parameter :: {block}({len(words)}) = [ &")
        out.extend(f"  {row}{', &' if i < len(rows) - 1 else ']'}" for i, row in enumerate(rows))
    lines = [", ".join(blocks[i : i + 6]) for i in range(0, len(blocks), 6)]
    out.append(f"integer(I8P), parameter :: {name}(1:2, {first}:{last}) = reshape([ &")
    out.extend(f"  {line}{', &' if i < len(lines) - 1 else '], [2, ' + str(last - first + 1) + '])'}" for i, line in enumerate(lines))
    return out


def module() -> str:
    """Return the text of the module."""
    head = [
        "!< Powers of ten of the number conversions of StringiFor, generated: do not edit.",
        "!<",
        "!< Generated by scripts/utf8/gen_number_tables.py. Columns: high and low 64 bits, as two's complement integers.",
        "module stringifor_number_tables",
        "!< Powers of ten of the number conversions of StringiFor, generated: do not edit.",
        "use penf, only : I8P",
        "",
        "implicit none",
        "private",
        "public :: POW5_TABLE",
        "public :: POW10_TABLE",
        "",
    ]
    body = table("POW5_TABLE", -342, 308, pow5) + table("POW10_TABLE", -292, 324, pow10)
    return "\n".join([*head, *body, "endmodule stringifor_number_tables", ""])


def main() -> int:
    """Write or check the module."""
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="compare with the committed module")
    args = parser.parse_args()
    text = module()
    if args.check:
        if MODULE.read_text(encoding="ascii") != text:
            print(f"{MODULE} is not what the generator gives", file=sys.stderr)
            return 1
        print("the number tables are up to date")
        return 0
    MODULE.write_text(text, encoding="ascii")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
